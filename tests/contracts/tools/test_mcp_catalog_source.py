"""Contract test for the standalone catalog server (V3.08/V3.10).

    uv run --env-file .env pytest tests/contracts/tools/test_mcp_catalog_source.py -q

The live ``tools/list`` must match the committed manifest exactly, including
the description and input schema that V3.10 pins.
"""

from __future__ import annotations

import os
from pathlib import Path

import pytest

from switchboard.adapters.tools.mcp_client import discover_tools
from switchboard.eval.manifest import load_tool_specs

REPO = Path(__file__).resolve().parents[3]
MCP_URL = os.environ.get("MCP_CATALOG_URL", "").rstrip("/")

pytestmark = [
    pytest.mark.integration,
    pytest.mark.skipif(not MCP_URL, reason="set MCP_CATALOG_URL"),
]


async def test_live_catalog_tools_match_the_manifest() -> None:
    manifest = load_tool_specs(REPO / "mcp_servers" / "catalog" / "manifest.yaml")
    live = await discover_tools(MCP_URL)
    assert {spec.wire_name for spec in live} == {spec.wire_name for spec in manifest}
    expected = {spec.wire_name: spec for spec in manifest}
    for spec in live:
        assert spec.description == expected[spec.wire_name].description
        assert spec.risk == "read"
    # The live input schema is generated by the MCP SDK and carries its own
    # titles and nullable wrappers; V3.10 pins the live schema, not the
    # handwritten manifest copy, so this test checks the contract fields the
    # model sees rather than byte equality with the manifest.
