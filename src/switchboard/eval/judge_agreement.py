"""Judge agreement run against a human-labeled sample (design.md section 6.8).

The sample lives in ``evals/judge/agreement.jsonl``. Its labels are the
author's, final, and are never regenerated by this code: the file is read, a
missing or unknown ``human_label`` refuses the run before any model call, and
the report prints the exact labels it compared.

The bar for trusting the judge is deliberately blunt and declared here, so the
report cannot quietly move it:

* raw agreement at least 0.90;
* Cohen's kappa at least 0.70 (chance-corrected agreement);
* zero false rejections of an answer the author labeled acceptable.

The command only reports. Enabling the judge is a config change
(``platform.judge.enabled``) that follows the report, not part of this run.
"""

from __future__ import annotations

import asyncio
import json
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any, Literal

from switchboard.core.config import PriceEntry
from switchboard.core.errors import ConfigError
from switchboard.core.models import (
    Citation,
    JudgeEvidence,
    JudgeRequest,
    JudgeVerdict,
    Usage,
)
from switchboard.core.ports import Judge
from switchboard.core.pricing import compute_cost
from switchboard.eval.scorers.judge import agreement_summary, confusion_matrix

DEFAULT_AGREEMENT_PATH = Path("evals/judge/agreement.jsonl")
DEFAULT_AGREEMENT_NAME = "judge-agreement"
MIN_RAW_AGREEMENT = 0.90
MIN_COHEN_KAPPA = 0.70

HumanLabel = Literal["acceptable", "weak"]


@dataclass(frozen=True)
class AgreementCase:
    case_id: str
    query: str
    answer: str
    evidence: list[JudgeEvidence]
    citations: list[Citation]
    human_label: HumanLabel
    note: str = ""


@dataclass(frozen=True)
class AgreementRun:
    case: AgreementCase
    verdict: JudgeVerdict | None = None
    error: str | None = None


def _parse_case(raw: Any, *, line: int) -> AgreementCase:
    if not isinstance(raw, dict):
        raise ConfigError(f"agreement line {line} is not a JSON object")
    case_id = raw.get("id")
    if not isinstance(case_id, str) or not case_id.strip():
        raise ConfigError(f"agreement line {line} needs a case id")
    label = raw.get("human_label")
    if label not in {"acceptable", "weak"}:
        raise ConfigError(
            f"case {case_id!r} needs a human_label of 'acceptable' or 'weak'; the label is "
            "author-provided and must never be regenerated"
        )
    query = raw.get("query")
    answer = raw.get("answer")
    if not isinstance(query, str) or not isinstance(answer, str):
        raise ConfigError(f"case {case_id!r} needs string query and answer fields")
    raw_evidence = raw.get("evidence", [])
    if not isinstance(raw_evidence, list):
        raise ConfigError(f"case {case_id!r} evidence must be a list")
    evidence: list[JudgeEvidence] = []
    for item in raw_evidence:
        if not isinstance(item, dict):
            raise ConfigError(f"case {case_id!r} evidence items must be objects")
        try:
            evidence.append(
                JudgeEvidence(kind=item["kind"], ref=item["ref"], text=item.get("text", ""))
            )
        except KeyError as exc:
            raise ConfigError(f"case {case_id!r} evidence is missing {exc}") from exc
    citations = [
        Citation(
            kind=item.kind,
            ref=item.ref,
            source_id=str(item.ref),
            snippet=item.text[:240] or item.ref,
        )
        for item in evidence
        if f"[{item.ref}]" in answer
    ]
    note = raw.get("note")
    return AgreementCase(
        case_id=case_id,
        query=query,
        answer=answer,
        evidence=evidence,
        citations=citations,
        human_label=label,
        note=note if isinstance(note, str) else "",
    )


def load_agreement(path: Path) -> list[AgreementCase]:
    """Read every labeled case, refusing the file when any label is missing."""
    source = Path(path)
    if not source.is_file():
        raise ConfigError(f"no judge agreement sample at {source}")
    cases: list[AgreementCase] = []
    seen: set[str] = set()
    for line_number, line in enumerate(source.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            raw = json.loads(line)
        except json.JSONDecodeError as exc:
            raise ConfigError(f"{source} line {line_number} is not valid JSON: {exc}") from exc
        case = _parse_case(raw, line=line_number)
        if case.case_id in seen:
            raise ConfigError(f"duplicate agreement case id {case.case_id!r}")
        seen.add(case.case_id)
        cases.append(case)
    if not cases:
        raise ConfigError(f"{source} has no agreement cases")
    return cases


async def run_agreement(judge: Judge, cases: Sequence[AgreementCase]) -> list[AgreementRun]:
    """One judge call per case, sequentially.

    Sequential on purpose: the sample is small and the latency of one judge call
    on the local model is part of the measurement, so concurrent calls would
    make it meaningless.
    """
    runs: list[AgreementRun] = []
    for case in cases:
        request = JudgeRequest(
            query=case.query,
            answer=case.answer,
            evidence=list(case.evidence),
            citations=list(case.citations),
        )
        try:
            verdict = await judge.judge(request)
        except Exception as exc:
            runs.append(AgreementRun(case=case, error=f"{type(exc).__name__}: {exc}"))
            continue
        runs.append(AgreementRun(case=case, verdict=verdict))
    return runs


def _labels(cases: Sequence[AgreementCase], label: str) -> list[str]:
    return [case.case_id for case in cases if case.human_label == label]


def _usage(runs: Sequence[AgreementRun]) -> Usage:
    total = Usage(input_tokens=0, output_tokens=0)
    for run in runs:
        if run.verdict is not None and run.verdict.usage is not None:
            total = total.plus(run.verdict.usage)
    return total


def _cost(runs: Sequence[AgreementRun], price: PriceEntry | None) -> float | None:
    if price is None:
        return None
    total = 0.0
    reported = False
    for run in runs:
        if run.verdict is None:
            continue
        if run.verdict.cost_usd is not None:
            total += run.verdict.cost_usd
            reported = True
        elif run.verdict.usage is not None:
            total += compute_cost(run.verdict.usage, price)
            reported = True
    return round(total, 12) if reported else None


def build_agreement_report(
    *,
    cases: Sequence[AgreementCase],
    runs: Sequence[AgreementRun],
    dataset_path: str,
    provider: str,
    model: str,
    judge_name: str,
    threshold: float,
    price: PriceEntry | None,
    judge_enabled: bool,
    generated_at: datetime,
    wall_time_s: float,
) -> dict[str, Any]:
    pairs = [(run.case.human_label, run.verdict.verdict) for run in runs if run.verdict is not None]
    metrics = agreement_summary(pairs)
    metrics["errors"] = float(sum(1 for run in runs if run.error))
    usage = _usage(runs)
    false_rejections = [
        run.case.case_id
        for run in runs
        if run.verdict is not None
        and run.case.human_label == "acceptable"
        and run.verdict.verdict == "weak"
    ]
    missed_weak = [
        run.case.case_id
        for run in runs
        if run.verdict is not None
        and run.case.human_label == "weak"
        and run.verdict.verdict == "acceptable"
    ]
    meets_bar = (
        len(pairs) == len(cases)
        and metrics["raw_agreement"] >= MIN_RAW_AGREEMENT
        and metrics["cohen_kappa"] >= MIN_COHEN_KAPPA
        and not false_rejections
    )
    report: dict[str, Any] = {
        "suite": "judge-agreement",
        "dataset_path": dataset_path,
        "case_count": len(cases),
        "judged_cases": len(pairs),
        "provider": provider,
        "model": model,
        "judge": judge_name,
        "threshold": threshold,
        "generated_at": generated_at.isoformat(),
        "wall_time_s": round(wall_time_s, 3),
        "label_source": ("author-provided human labels, final, not regenerated by this run"),
        "metrics": metrics,
        "confusion_matrix": confusion_matrix(pairs),
        "labels": {
            "acceptable": _labels(cases, "acceptable"),
            "weak": _labels(cases, "weak"),
        },
        "false_rejection_cases": false_rejections,
        "missed_weak_cases": missed_weak,
        "decision": {
            "raw_agreement_min": MIN_RAW_AGREEMENT,
            "cohen_kappa_min": MIN_COHEN_KAPPA,
            "false_rejections_max": 0,
            "met": meets_bar,
            "judge_enabled_in_config": judge_enabled,
        },
        "usage": {
            "input_tokens": usage.input_tokens,
            "cached_input_tokens": usage.cached_input_tokens,
            "output_tokens": usage.output_tokens,
            "total_tokens": usage.total_tokens,
        },
        "cost_usd": _cost(runs, price),
        "no_api_cost": bool(price is not None and price.is_zero),
        "latency_ms": [run.verdict.latency_ms if run.verdict else 0 for run in runs],
        "cases": [
            {
                "case_id": run.case.case_id,
                "query": run.case.query,
                "answer": run.case.answer,
                "human_label": run.case.human_label,
                "judge_label": run.verdict.verdict if run.verdict else None,
                "judge_score": run.verdict.score if run.verdict else None,
                "agree": bool(run.verdict and run.verdict.verdict == run.case.human_label),
                "reason": run.verdict.reason if run.verdict else "",
                "latency_ms": run.verdict.latency_ms if run.verdict else 0,
                "note": run.case.note,
                "error": run.error,
            }
            for run in runs
        ],
        "error_count": sum(1 for run in runs if run.error),
        "error_case_ids": [run.case.case_id for run in runs if run.error],
    }
    return report


def _cell(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def render_agreement_markdown(report: dict[str, Any]) -> str:
    metrics = report["metrics"]
    matrix = report["confusion_matrix"]
    lines = [f"# Judge agreement: {report['provider']}", ""]
    lines.append("## Run")
    lines.append("")
    lines.append(f"- Sample: `{report['dataset_path']}` ({report['case_count']} cases)")
    lines.append(
        f"- Judge: `{report['judge']}` on provider `{report['provider']}`, "
        f"model `{report['model']}`"
    )
    lines.append(f"- Score threshold for an acceptable verdict: {report['threshold']}")
    lines.append(f"- Generated: {report['generated_at']}")
    lines.append(f"- Wall time: {report['wall_time_s']} s")
    lines.append(f"- Labels: {report['label_source']}")
    lines.append("")
    lines.append("## Agreement")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("| --- | --- |")
    integer_metrics = {"cases", "agreements", "false_rejections", "missed_weak", "errors"}
    for name in (
        "cases",
        "agreements",
        "raw_agreement",
        "cohen_kappa",
        "false_rejections",
        "missed_weak",
        "judge_accept_rate",
        "errors",
    ):
        value = metrics.get(name)
        if name in integer_metrics:
            rendered = str(int(value)) if value is not None else "0"
        elif isinstance(value, float):
            rendered = f"{value:.4f}"
        else:
            rendered = str(value)
        lines.append(f"| {name} | {rendered} |")
    lines.append("")
    lines.append("## Confusion matrix")
    lines.append("")
    lines.append("| Human \\ Judge | acceptable | weak |")
    lines.append("| --- | --- | --- |")
    for human in ("acceptable", "weak"):
        row = matrix[human]
        lines.append(f"| {human} | {row['acceptable']} | {row['weak']} |")
    lines.append("")
    lines.append("## Labels")
    lines.append("")
    lines.append(
        f"- Acceptable ({len(report['labels']['acceptable'])}): "
        + (", ".join(report["labels"]["acceptable"]) or "none")
    )
    lines.append(
        f"- Weak ({len(report['labels']['weak'])}): "
        + (", ".join(report["labels"]["weak"]) or "none")
    )
    lines.append("")
    lines.append(
        "False rejections (human acceptable, judge weak): "
        + (", ".join(report["false_rejection_cases"]) or "none")
        + ". Missed weak answers (human weak, judge acceptable): "
        + (", ".join(report["missed_weak_cases"]) or "none")
        + "."
    )
    lines.append("")
    decision = report["decision"]
    lines.append("## Decision")
    lines.append("")
    lines.append(
        f"Bar: raw agreement at least {decision['raw_agreement_min']}, Cohen's kappa at "
        f"least {decision['cohen_kappa_min']}, and no false rejection. This run "
        + ("meets the bar." if decision["met"] else "does not meet the bar.")
    )
    lines.append(
        "`platform.judge.enabled` was "
        + ("true" if decision["judge_enabled_in_config"] else "false")
        + " when this report was written. The judge runs in production only when that "
        "setting is true; changing it is a config edit that follows this report."
    )
    lines.append("")
    lines.append("## Latency")
    lines.append("")
    latencies = [int(value) for value in report["latency_ms"] if value]
    if latencies:
        ordered = sorted(latencies)
        p50 = ordered[len(ordered) // 2]
        lines.append("| Calls | p50 ms | min ms | max ms | mean ms |")
        lines.append("| --- | --- | --- | --- | --- |")
        lines.append(
            f"| {len(latencies)} | {p50} | {ordered[0]} | {ordered[-1]} | "
            f"{round(sum(ordered) / len(ordered), 1)} |"
        )
    else:
        lines.append("No judge call returned a latency.")
    lines.append("")
    lines.append("## Usage")
    lines.append("")
    lines.append("| Input tokens | Cached input tokens | Output tokens | Total tokens |")
    lines.append("| --- | --- | --- | --- |")
    usage = report["usage"]
    lines.append(
        f"| {usage['input_tokens']} | {usage['cached_input_tokens']} | "
        f"{usage['output_tokens']} | {usage['total_tokens']} |"
    )
    lines.append("")
    if report["cost_usd"] is None:
        lines.append("Cost is not reported: the provider has no row in `config/prices.yaml`.")
    elif report["no_api_cost"]:
        lines.append(
            f"Cost: USD {report['cost_usd']:.6f}. The provider is local (LM Studio), so "
            "the run has no API cost; the price table records zero for it on purpose."
        )
    else:
        lines.append(f"Cost: USD {report['cost_usd']:.6f} from `config/prices.yaml`.")
    lines.append("")
    lines.append(f"## Cases ({report['case_count']})")
    lines.append("")
    lines.append("| Case | Human | Judge | Agree | Score | Latency ms | Reason |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- |")
    for case in report["cases"]:
        score = "" if case["judge_score"] is None else f"{case['judge_score']:.2f}"
        lines.append(
            "| "
            + " | ".join(
                [
                    _cell(case["case_id"]),
                    _cell(case["human_label"]),
                    _cell(case["judge_label"] or "error"),
                    "yes" if case["agree"] else "no",
                    score,
                    str(case["latency_ms"]),
                    _cell(case["reason"] or case["error"] or ""),
                ]
            )
            + " |"
        )
    lines.append("")
    lines.append(f"Errors: {report['error_count']}")
    lines.append("")
    return "\n".join(lines)


def write_agreement_report(
    report: dict[str, Any], output_dir: Path, *, name: str = DEFAULT_AGREEMENT_NAME
) -> tuple[Path, Path]:
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    markdown_path = output / f"{name}.md"
    json_path = output / f"{name}.json"
    markdown_path.write_text(render_agreement_markdown(report), encoding="utf-8", newline="\n")
    json_path.write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )
    return markdown_path, json_path


def run_agreement_sync(judge: Judge, cases: Sequence[AgreementCase]) -> list[AgreementRun]:
    """Blocking wrapper for the CLI, which is synchronous."""
    return asyncio.run(run_agreement(judge, cases))


